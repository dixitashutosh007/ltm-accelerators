/**
 * The FinOps IQ consultant playbook (execution phase M8: "playbook regenerated from the engine and KB"). Every line
 * comes from what the engine runs on: the question bank, capability model, levers, engine and value rules, the
 * platform playbook, the offering catalogue and the client notices. Nothing is written by hand, so the playbook
 * cannot drift from the engine the way the superseded v2.2 playbook did.
 * Written to docs/cio-readiness/finops-iq/CONSULTANT_PLAYBOOK.md by `npm run build:finops-iq-playbook`; a test fails
 * CI when the file is out of date. The playbook is internal: it lives in docs/, not in the hosted Accelerators/.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import bank from '../packages/engine-core/src/accelerators/finops-iq/v3/question-bank.json' with { type: 'json' };
import engineRules from '../packages/engine-core/src/accelerators/finops-iq/v3/engine-rules.json' with { type: 'json' };
import valueRules from '../packages/engine-core/src/accelerators/finops-iq/v3/value-rules.json' with { type: 'json' };
import capabilityModel from '../packages/engine-core/src/accelerators/finops-iq/registry/capabilities.json' with { type: 'json' };
import leverLibrary from '../packages/engine-core/src/accelerators/finops-iq/registry/levers.json' with { type: 'json' };
import platformPlaybook from '../packages/engine-core/src/playbook/finops-iq.json' with { type: 'json' };
import offerings from '../packages/engine-core/src/offerings/finops-iq.json' with { type: 'json' };
import register from '../packages/engine-core/src/claims/claims-register.json' with { type: 'json' };
import { ENGINE_VERSION } from '../packages/engine-core/src/accelerators/finops-iq/v3/evaluate';
import { NOTICES, PLATFORM_LABELS } from '../packages/engine-core/src/accelerators/finops-iq/v3/public-schema';
import { RETENTION_MONTHS } from '../packages/engine-core/src/accelerators/finops-iq/v3/retention';

const B: any = bank, ER: any = engineRules, VR: any = valueRules, CM: any = capabilityModel, LV: any = leverLibrary;
const PB: any = platformPlaybook, OF: any = offerings, REG: any = register;

export const PLAYBOOK_FILE = fileURLToPath(new URL('../docs/cio-readiness/finops-iq/CONSULTANT_PLAYBOOK.md', import.meta.url));

const LEVEL = { not_yet: 'Not yet', crawl: 'Crawl', walk: 'Walk', run: 'Run', unknown: "Don't know" } as Record<string, string>;
const PROVIDER = { aws: 'AWS', azure: 'Azure', gcp: 'Google Cloud', oci: 'OCI', ibm: 'IBM Cloud', alibaba: 'Alibaba Cloud', other_public: 'Other public cloud' } as Record<string, string>;
const cell = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const pct = (x: number) => `${Math.round(x * 1000) / 10}%`;
/** Year 1 may be the share of spend renewing in year 1 (LEV-09), with a fallback share when renewal dates are unknown. */
const year1 = (r: any) => (typeof r.year1Share === 'number' ? pct(r.year1Share) : `the share renewing in year 1 (${pct(r.year1ShareWithoutRenewalData)} when renewal dates are unknown)`);
/** Need-index modifier IDs in words, e.g. expected_value_ge_5pct_of_P. */
const modifier = (id: string) => id.replace(/_/g, ' ').replace(/\bge\b/, 'at least').replace(/(\d+)pct/, '$1%').replace(/\bof P\b/, 'of in-scope public cloud spend');
const table = (head: string[], rows: unknown[][]) =>
  [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(r => `| ${r.map(cell).join(' | ')} |`)].join('\n');
const QUESTION = new Map<string, any>(B.questions.map((q: any) => [q.id, q]));
const CAP = new Map<string, any>(CM.capabilities.map((c: any) => [c.id, c]));
const modes = (q: any) => (q.modes.length === 2 ? 'both' : q.modes[0]);
const citations = (q: any) => [...new Set((q.basis ?? []).map((b: any) => b.claimId))].join(', ');

function question(q: any): string {
  const out = [`**${q.id}** (${modes(q)}${q.role ? `, ${q.role.replace(/_/g, ' ')}` : ''}). ${q.text}`];
  if (q.help) out.push(`  *How to ask:* ${q.help}`);
  if (q.options?.length) out.push(...q.options.map((o: any) => `  - ${o.label}${o.level ? ` → ${LEVEL[o.level] ?? o.level}` : ''}`));
  if (q.basis?.length) out.push(`  *Basis:* ${citations(q)}`);
  return out.join('\n');
}

function maxRate(l: any): string {
  const m = l.maxRate;
  if (m.kind === 'published_by_provider') {
    return Object.entries<any>(m.byProvider).map(([p, v]) => `${PROVIDER[p] ?? p}: ${v.quantified ? pct(v.value) : 'not quantified'}`).join('; ');
  }
  return typeof m.value === 'number' ? `${m.kind.replace(/_/g, ' ')}, up to ${pct(m.value)}` : m.kind.replace(/_/g, ' ');
}

export function buildPlaybook(): string {
  const exec = new Set<string>(B.executiveSet);
  const s: string[] = [];
  s.push('# FinOps IQ consultant playbook');
  s.push('');
  s.push('> Generated by `npm run build:finops-iq-playbook` from the engine and its knowledge base. Do not edit by hand: change the source and regenerate. Internal to LTM consultants; the client sees the page and the report, not this playbook.');
  s.push('');
  s.push(table(['Source', 'Version'], [
    ['FinOps IQ engine', ENGINE_VERSION], ['Question set', B.questionSetVersion], ['Capability model', CM.modelVersion],
    ['Lever library', LV.libraryVersion], ['Engine rules', ER.rulesVersion], ['Value rules', VR.rulesVersion],
    ['Platform playbook', PB.catalogueVersion], ['Offering catalogue', OF.catalogueVersion], ['Claims register', REG.version]
  ]));

  s.push('', '## 1. What FinOps IQ answers', '');
  s.push(`FinOps IQ rates the client's FinOps capabilities on the FinOps Foundation's Crawl, Walk, Run scale (plus "Not yet"), sets each against a default target for the estate's complexity tier, and sizes the value of closing the gaps as a conservative, expected and upper range, net of implementation effort. It has two modes:`);
  s.push('');
  s.push(`- **Executive** (${exec.size} questions): do we need to act now, and roughly how much is at stake? For the CIO or CFO. It replaces the former FinOps Value Case.`);
  s.push(`- **Workshop** (up to ${B.questions.length} questions, asked only where the estate makes them apply): what exactly, by when, owned by whom, and what is it worth? Consultant-led with the cloud, FinOps, finance and engineering leads. An executive assessment can be continued in the workshop with its answers carried over.`);
  s.push('', 'Scoring runs on the LTM service, never in the browser. A completed assessment is recorded and cannot be changed; start a new one to revise it.');

  s.push('', '## 2. What to tell the client', '');
  s.push('Read these as they stand; they are the approved wording shown on the start screen and in the report.', '');
  s.push(`**How the data is handled.** ${NOTICES.data}`, '');
  s.push(`**Disclaimer.** ${NOTICES.disclaimer}`, '');
  s.push(`**Framework.** ${NOTICES.attribution} (${NOTICES.attributionLinks.map(l => `[${l.label}](${l.url})`).join(', ')})`, '');
  s.push(`Assessments are kept for ${RETENTION_MONTHS} months after their last change and then deleted; delete one sooner from the assessment list when the client asks.`);

  s.push('', '## 3. How to talk about value', '');
  s.push(`- Every figure carries the label: "${VR.labels.headline}". ${VR.labels.detail}`);
  s.push(`- Cases: expected = ${pct(LV.rangeRule.expectedFactor)} of each lever's maximum rate, conservative = ${pct(LV.rangeRule.conservativeFactor)}; the upper case uses the maximum. Public cloud levers together are capped at ${pct(LV.globalCap.shareOfPublicCloudSpend)} of in-scope public cloud spend (${LV.globalCap.source.citation}).`);
  s.push(`- ${VR.labels.withheld}`);
  s.push('- Say "indicative" and "range", and point to the evidence that would firm it up (section 7). Never present the range as a promise, as a sum already lost, or as a FinOps Foundation result. `scripts/check-claims.cjs` holds the phrases that must not appear in client-facing text.');
  s.push('- A blank answer or "Don\'t know" is rated as unconfirmed and never raises a value. The client\'s own estimate of waste is never used in a figure.');

  s.push('', '## 4. Run of show', '');
  s.push('1. **Engagement setup** (consultant only): the client\'s loaded internal cost per FTE-month. Without it no money figure is shown.');
  s.push('2. **Your estate**: providers, scopes, spend by scope, growth and the consuming units. These decide which capabilities and questions apply; they are never scored.');
  CM.domains.forEach((d: any, i: number) => s.push(`${i + 3}. **${d.name}**: ${d.capabilities.map((c: string) => CAP.get(c)?.displayName ?? c).join(', ')}.`));
  s.push(`${CM.domains.length + 3}. **Value inputs**: the shares and evidence each lever needs (section 7).`);
  s.push(`${CM.domains.length + 4}. **Results**, then **Complete**: the server records the result and dates it. Then download the report (client or consultant edition) and the backlog CSV, archive the PDF to Reports if wanted, and use client view (with teaser mode if the readout comes later) on screen.`);

  s.push('', '## 5. Questions', '');
  s.push('### 5.1 Estate and value inputs (never scored)', '');
  for (const q of B.questions.filter((x: any) => x.kind === 'scope' || x.kind === 'value_base')) s.push(question(q), '');
  for (const d of CM.domains) {
    s.push(`### ${d.name}`, '');
    for (const id of d.capabilities) {
      const c = CAP.get(id);
      if (!c) continue;
      const t = c.defaultTargets ?? {};
      s.push(`#### ${c.displayName}`, '');
      s.push(c.description, '');
      s.push(`Default target by tier: Tier 1 ${LEVEL[t.tier1] ?? '—'}, Tier 2 ${LEVEL[t.tier2] ?? '—'}, Tier 3 ${LEVEL[t.tier3] ?? '—'}${t.runReason ? ` (${t.runReason})` : ''}. Owner: ${ER.ownerRoles.byCapability[id] ?? '—'}.`, '');
      const g = c.maturityGuidance ?? {};
      s.push(table(['Not yet', 'Crawl', 'Walk', 'Run'], [[g.notYet, g.crawl, g.walk, g.run]]), '');
      const ct = ER.capabilityText.byCapability[id];
      if (ct) s.push(`*If below target:* ${ct.consequence} *Evidence to ask for:* ${ct.evidence}`, '');
      for (const ref of c.questions) { const q = QUESTION.get(ref.id); if (q) s.push(question(q), ''); }
    }
  }
  const hyp = B.questions.filter((x: any) => x.kind === 'hypothesis');
  if (hyp.length) { s.push('### Hypothesis (recorded, never an input)', ''); for (const q of hyp) s.push(question(q), ''); }

  s.push('## 6. How the result is built', '');
  s.push(`- **Severity** of a capability gap: ${Object.entries<string>(ER.severity.byGap).map(([g, v]) => `${g} level${g === '1' ? '' : 's'} below target = ${v}`).join('; ')}. Raised one step for ${ER.severity.foundationUplift.capabilities.map((c: string) => CAP.get(c)?.displayName ?? c).join(', ')} from Tier ${ER.severity.foundationUplift.minTier}.`);
  s.push(`- **Roadmap pace**: a gap moves one level at a time: the first level ${ER.schedule.firstMilestoneMonths} months after it starts, each further level ${ER.schedule.levelStepMonths} months later.`);
  s.push(`- **Need verdict** (executive mode): a need index out of ${ER.needVerdict.cap}, raised by ${ER.needVerdict.modifiers.map((m: any) => `${modifier(m.id)} (+${m.points})`).join(', ')}. Bands: ${ER.needVerdict.bands.map((b: any) => `up to ${b.max} "${b.label}"`).join('; ')}.`);
  for (const d of ER.decisions) {
    s.push(`- **${d.title}** (${d.severity}): raised when ${d.question} is answered ${d.levels.map((l: string) => LEVEL[l] ?? l.replace(/_/g, ' ')).join(', ')}. Action: ${d.action}.`);
  }
  s.push(`- **${VR.decision02.title}**: ${VR.decision02.consequence} Action: ${VR.decision02.action}.`);

  s.push('', '## 7. Value levers', '');
  for (const l of LV.levers) {
    s.push(`### ${l.id} ${l.name}`, '');
    s.push(table(['', ''], [
      ['Type and capability', `${l.type}; ${CAP.get(l.capability)?.displayName ?? l.capability}`],
      ['Quantified in', (l.quantifiedIn ?? []).join(', ') || '—'],
      ['Addressable base', l.addressableBase?.formula ?? '—'],
      ['Maximum rate', maxRate(l)],
      ['Evidence age limit', l.evidenceFreshnessDays ? `${l.evidenceFreshnessDays} days` : '—'],
      ['Ramp (share of run-rate)', l.ramp ? `year 1 ${year1(l.ramp)}, year 2 ${pct(l.ramp.year2Share)}, year 3 ${pct(l.ramp.year3Share)}` : '—'],
      ['Internal effort (FTE-months)', l.effortFteMonths ? `Tier 1 ${l.effortFteMonths.tier1}, Tier 2 ${l.effortFteMonths.tier2}, Tier 3 ${l.effortFteMonths.tier3}; ongoing ${pct(l.effortFteMonths.ongoingShareOfOneOff)} a year` : '—'],
      ['Confidence', l.confidenceRule ?? '—'],
      ['What the client sees', l.label ?? '—']
    ]), '');
  }

  s.push('## 8. Consultant checks', '');
  s.push('Answers that contradict each other raise these probes on the consultant\'s screen and in the consultant edition only:', '');
  for (const p of B.conflictProbes) s.push(`- **${p.id}**: ${p.probe}`);

  s.push('', '## 9. Technical execution', '');
  s.push(`The report adds platform actions from the platform playbook (${PB.entries.length} entries) for the platforms the client has, each with a verification step. Controls covered:`, '');
  const byControl = new Map<string, any[]>();
  for (const e of PB.entries) byControl.set(e.control, [...(byControl.get(e.control) ?? []), e]);
  s.push(table(['Control', 'Entries', 'Platforms'], [...byControl].map(([c, es]) => [
    c.replace(/^FIN\./, '').replace(/_/g, ' ').replace(/^LEV-(\d+)$/, m => `${m} ${LV.levers.find((l: any) => l.id === m)?.name ?? ''}`.trim()),
    es.length, [...new Set(es.map(e => PLATFORM_LABELS[e.platform] ?? PROVIDER[e.platform] ?? e.platform))].join(', ')
  ])));
  s.push('', 'Capabilities outside these controls have no platform entry yet; the finding\'s own action and evidence apply.');

  s.push('', '## 10. How LTM can help', '');
  s.push('Findings map to these offerings. Indicative scope is an LTM heuristic to be agreed per engagement, shown in the consultant edition only; the SOW draft is subject to contract.', '');
  for (const o of OF.offerings) {
    s.push(`- **${o.name}** (${o.type}, ${o.practice}): ${o.purpose}${o.indicativeScope ? ` Indicative scope: ${o.indicativeScope}.` : ''}`);
  }

  s.push('', '## 11. Sources', '');
  const fin = REG.claims.filter((c: any) => c.accelerators?.includes('finops-iq'));
  const by = (v: string) => fin.filter((c: any) => c.verification === v).length;
  s.push(`FinOps IQ rests on ${fin.length} claims in \`packages/engine-core/src/claims/claims-register.json\`: ${by('V')} verified against the source (V), ${by('S')} from a secondary source (S), ${by('P')} pending (P), and ${fin.length - by('V') - by('S') - by('P')} LTM heuristics or other statuses. Each question above lists its claim IDs; the report's methodology appendix cites them for the client.`);
  return s.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
}

if (process.argv[1] && /build-finops-iq-playbook/.test(process.argv[1])) {
  writeFileSync(PLAYBOOK_FILE, buildPlaybook());
  console.log(`Wrote ${PLAYBOOK_FILE}`);
}
